/* Formats a float as "-12.34" into buf using only integer sprintf
 * specifiers (%d) — sidesteps needing the newlib-nano "-u _printf_float"
 * linker flag, which wasn't taking effect on this project. Always
 * writes exactly 2 decimal digits.
 * NOTE: no longer static — freertos.c (UartTask) calls this too.
 * Declared in main.h so both files can see it. */
void format_float2(char *buf, float val)
{
    int sign = (val < 0) ? -1 : 1;
    float absVal = val * sign;
    int whole = (int)absVal;
    int frac = (int)((absVal - whole) * 100.0f + 0.5f); /* round to 2 dp */
    if (frac >= 100) { frac -= 100; whole += 1; }        /* carry from rounding */
    sprintf(buf, "%s%d.%02d", (sign < 0) ? "-" : "", whole, frac);
}

